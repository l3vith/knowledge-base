"""Deterministic fact inventory: which verified source sentences an analytical answer must carry.

Code, not the writer, decides content: a sentence is a fact when it states a result with a quantity (a number with
a unit or a comparison) or a limitation/condition. Writers then phrase these facts, and a coverage check puts back,
verbatim, any fact the written answer lost. Background (definitions, literature, method recipes) is not a fact."""
import re
from .utils import display_source

_NOISE = re.compile(r"<sup>.*?</sup>|\[\d+(?:\s*[,–-]\s*\d+)*\]|\(\s*\d+(?:\.\d+)*\s*\)|\b(?:19|20)\d{2}\b|"
                    r"\b(?:Section|Sections|Figure|Figures|Fig\.|Table|Tables|Equation|Eq\.|Theorem|Chapter|Appendix)\s*\d+(?:\.\d+)*")
_QUANTITY = re.compile(r"\d(?:[\d,.]*\d)?\s*(?:%|percent|times|x\b|×|ms\b|milliseconds?|microseconds?|µs|seconds?|\bs\b|minutes?|"
                       r"hours?|days?|weeks?|months?|years?|KB|MB|GB|calls?|points?|paths?|surfaces?|evaluations?|"
                       r"samples?|parameters?|dimensions?|ranks?|cores?|ppts?|bps|basis points|million|billion|USD|EUR|GBP|INR)", re.I)
_LIMIT = re.compile(r"\b(?:cannot|can ?not|not (?:be |been |possible|guaranteed|known|tested|shown|clear)|no (?:guarantee|"
                    r"convergence|extrapolation)|only (?:inside|within|for|if|when|valid)|outside|extrapolat\w*|limitation\w*|"
                    r"drawback\w*|caveat\w*|assum\w*|unknown|do not know|future work|rebuil\w*|must|should|preferable|"
                    r"recommend\w*|depend\w* on|sensitive|instabilit\w*|unstable|bias\w*|risk\w*)\b", re.I)
# Test conditions the answer must state: hardware, data and tested scope.
_SETUP = re.compile(r"\b(?:GPUs?|CPUs?|cores|parallelis\w*|parallel|hardware|standard PC|synthetic\w*|market data)\b", re.I)
# Qualitative findings a theory paper is made of: what a parameter or variable does, and evidence the source cites
# ("σ increases the kurtosis", "positive correlation ... increases the prices of out-of-the-money options",
# "Lamoureux and Lastrapes (1993) present evidence that ..."). Without these, C17 (Heston) kept 15 facts and missed
# most of its benchmark; on C18 they add 11 of 79 facts.
_EFFECT = re.compile(r"\b(?:increase[sd]?|decrease[sd]?|raises?|lowers?|reduces?|spreads?|affects?|controls?|determines?|up|down|"
                     r"drives?|depends? on|leads? to|results? in|causes?|implies|is equivalent to|positively|negatively|"
                     r"has (?:little|no|a) (?:substantial |significant )?effect|fat (?:left|right) tail|"
                     r"presents? evidence|reports? that|reported that|finds? that|found that|shows? that|demonstrates?)\b", re.I)
_BACKGROUND = re.compile(r"^(?:\*\*|#)|\b(?:is defined as|we define|let us|in this paper we|this paper|the rest of the paper|"
                         r"is organi[sz]ed|see \[|following \[|for example|e\.g\.)", re.I)
_STRONG_UNIT = re.compile(r"%|percent|times|x\b|×|ms\b|milli|micro|µs|seconds?|\bs\b|minutes?|hours?|days?|weeks?|months?|years?|"
                          r"KB|MB|GB|ppts?|bps|basis points|million|billion|USD|EUR|GBP|INR", re.I)
_SMALL_RESULT = re.compile(r'\b(?:maximum|minimum|rank|dimension|parameters?)\b.{0,55}\b\d+(?:\.\d+)?\b|'
                           r'\b\d+\s+(?:parameters?|dimensions?|ranks?)\b', re.I)


def is_fact(sentence):
    """A result with a quantity (a time, size, share or money unit, or a count of 100 or more such as "14,400
    points" / "10,000 calls"), or a stated limitation/condition. Small counts ("7 points per dimension") are setup."""
    text = display_source(sentence)
    if len(text) < 8 or (_BACKGROUND.search(text) and not (_EFFECT.search(text) or _LIMIT.search(text))):
        return False
    clean = _NOISE.sub(" ", text)
    for m in _QUANTITY.finditer(clean):
        number = float(re.sub(r"[^\d.]", "", m.group().split()[0].rstrip(".")) or 0) if re.match(r"[\d,.]+", m.group()) else 0
        if _STRONG_UNIT.search(m.group()) or number >= 100:
            return True
    # A bare count of 1,000 or more ("only 20,000 were evaluated") is a result figure too.
    if any(float(n.replace(",", "")) >= 1000 for n in re.findall(r"\b\d{1,3}(?:,\d{3})+\b|\b\d{4,}\b", clean)):
        return True
    return bool(_LIMIT.search(clean) or _SETUP.search(clean) or _EFFECT.search(clean) or _SMALL_RESULT.search(clean))


# Never an answer on their own: train/test splits, measurement or sampling procedure, and sentences describing a
# plot rather than a result. Repeats of the same figures are one fact. Kept on purpose: a second case with different
# figures (it may be the one asked about, or the comparison) and the source's own guidance ("it is preferable to ...").
_SPLIT = re.compile(r"\btrain\w*\b.{0,80}\btest\w*\b|\btest\w*\b.{0,80}\btrain\w*\b", re.I | re.S)
_PROCEDURE = re.compile(r"\b(?:obtained by|randomly sampl\w*|uniform distribution|we do the following|the index\b|runs through|"
                        r"generated by specifying|must be specified|one must choose|is measured by comparing|was measured by comparing|"
                        r"per dimension|that is, evaluating)", re.I)
_PLOT = re.compile(r"^\s*(?:\*\*)?(?:Figures?|Fig\.|Table)\s*\d|\b(?:plots?|vertical line|horizontal line|heat ?maps?|x-axis|y-axis)\b", re.I)


def trim_secondary(facts,query=''):
    """Drop facts that are setup or presentation, not findings, and later repeats of the same figures.
    Returns (kept, [(fact, reason)])."""
    kept, trimmed = [], []
    words = lambda s: set(re.findall(r"[a-z]{4,}", s.casefold()))
    validation_requested=bool(re.search(r'validat|monitor|controls?|soundness|train|test|method|setup|sampl|reproduc',query,re.I))
    method_requested=bool(re.search(r'method|setup|sampl|reproduc|how .*work|mechanic|deriv',query,re.I))
    for f in facts:
        text, figures = f["text"], numbers(f["text"])
        data_procedure=validation_requested and bool(re.search(r'sampl|synthetic|market data|training|testing',text,re.I))
        reason = ("train/test split" if _SPLIT.search(text) and not validation_requested else "procedure" if _PROCEDURE.search(text) and not (method_requested or data_procedure)
                  else "plot description" if _PLOT.search(text) else None)
        if reason is None and figures:
            twin = next((k for k in kept if numbers(k["text"]) == figures and k["doc_id"] == f["doc_id"]
                         and k.get('scope')==f.get('scope') and polarity(k['text'])==polarity(text)
                         and len(words(k["text"]) & words(text)) >= 0.3 * len(words(k["text"]) | words(text))), None)
            reason = "repeat of " + twin["id"] if twin else None
        (trimmed.append((f, reason)) if reason else kept.append(f))
    return kept, trimmed


_AXIS_TERMS=(
    (r'accur|precision|recall|error|outcomes|validat',r'accur|error|rmse|quantile|validat|synthetic'),
    (r'speed|latency|runtime|throughput',r'speed|faster|runtime|seconds?|minutes?|hours?|processor|parallel|gpu'),
    (r'cost|build|construction|training',r'cost|build|construction|calls|grid|points|rank|memory|footprint|offline|reuse'),
    (r'limit|caveat|assum|outside|domain',r'limit|caveat|cannot|not know|unknown|domain|extrapolat|convergence'),
    (r'soundness',r'synthetic|assum|domain|tested|approximat'),
    (r'monitor',r'market|rebuild|change|weeks|months|reuse'),
    (r'control|safeguard|requirement',r'domain|constraint|test|validat|project|expect|rebuild|fallback'),
)


def select_facts(facts,query,topics,max_chars):
    """A shared source budget; reserve coverage and limitations before extra detail.

    Local topic hits guide selection, never certify support. IDs and input order do
    not decide retention. Only selected facts are mandatory for writer restoration.
    """
    remaining=sorted(facts,key=lambda f:(f.get('doc_id',''),f.get('page') or 0,
        f.get('char_start',0),f.get('section',''),f['text']))
    chosen=[];used=0;counts={};seen=set()
    def hits(f):
        text=f['text']+' '+f.get('section','')
        return {i for i,t in enumerate(topics) if any(re.search(a,t['text'],re.I) and re.search(b,text,re.I) for a,b in _AXIS_TERMS)}
    keys={f['id']:hits(f) for f in facts}
    def cost(f):return len(f['text'])+f.get('context_chars',0)
    def merit(f):
        gain=sum(1/(1+counts.get(t,0))**2 for t in keys[f['id']])
        novelty=len(numbers(f['text'])-seen)
        return (2*gain+.5*min(3,novelty)+.2)/max(60,cost(f))**.45
    def add(f):
        nonlocal used
        chosen.append(f);remaining.remove(f);used+=cost(f);seen.update(numbers(f['text']))
        for k in keys[f['id']]:counts[k]=counts.get(k,0)+1
    if re.search(r'limit|control|soundness|monitor|domain',query,re.I):
        reserve=int(max_chars*.2)
        while True:
            options=[f for f in remaining if _LIMIT.search(f['text']) and used+cost(f)<=reserve]
            if not options:break
            f=max(options,key=merit)
            if chosen and keys[f['id']] and all(counts.get(k,0) for k in keys[f['id']]):break
            add(f)
    while True:
        options=[f for f in remaining if used+cost(f)<=max_chars]
        if not options:break
        add(max(options,key=merit))
    ids={f['id'] for f in chosen}
    selected=[f for f in facts if f['id'] in ids]
    return selected,{'candidate_facts':len(facts),'selected_facts':len(selected),'source_chars':used,
        'source_char_cap':max_chars,'omitted_ids':[f['id'] for f in facts if f['id'] not in ids],
        'topic_candidate_hits':{t['id']:sum(i in k for k in keys.values()) for i,t in enumerate(topics)},
        'topic_selected_hits':{t['id']:counts.get(i,0) for i,t in enumerate(topics)},
        'warning':'Lexical selection coverage only; not gold recall or semantic support.'}


def numbers(text):
    """The figures a statement must keep: numbers outside footnotes, citations, years and Section/Figure labels."""
    return {n.replace(",", "") for n in re.findall(r"(?<![\w.])\d[\d,]*(?:\.\d+)?", _NOISE.sub(" ", display_source(text)))}


def states(statement, fact):
    """Conservative candidate coverage, never a semantic proof: figures AND substantive words.

    Previously an empty number set made *any* sentence carry a qualitative fact.
    Semantic verification must still approve the claim and its relation to the fact.
    """
    source=fact['text']
    if not numbers(source)<=numbers(statement):return False
    if polarity(source)!=polarity(statement):return False
    stop={'the','and','was','were','with','from','this','that','which','their','these','our','for','used','had','its','has','are','been','using','via','per','than','when','case','result','results'}
    def words(s):
        return {re.sub(r'(?:ing|ed|es|s)$','',w) for w in re.findall(r'[^\W\d_]+',s.casefold())
                if w not in stop and (len(w)>2 or not w.isascii())}
    expected=words(source);actual=words(statement)
    return bool(expected) and len(expected & actual)>=min(2,len(expected)) and len(expected & actual)/len(expected)>=.45


def polarity(text):
    """Negation and epistemic mode must not disappear during local deduplication."""
    return (bool(re.search(r'\b(?:no|not|never|cannot|without|neither|nor)\b',text,re.I)),
            bool(re.search(r'\b(?:assum\w*|expect\w*|project\w*|would|could|estimat\w*)\b',text,re.I)))


# A sentence that leans on the one before it (pronoun subject, lowercase continuation, "hence ...").
LEANS = re.compile(r"(?:[a-z]|(?:It|This|These|They|Its|Their|Such|Hence|Thus|Therefore|However|Here)\b)")


def inventory(numbered, spans, topics):
    """Facts in source order, each assigned to ONE topic (the verifier's requested-topic tag in query order, else the
    topic its words match, else its obligation) so exactly one writer is responsible for it. Exact repeats collapse."""
    words = lambda s: set(re.findall(r"[a-z]{4,}", s.casefold()))
    order = {t["id"]: i for i, t in enumerate(topics)}
    facts, seen = [], set()
    ranked = sorted(numbered.items(), key=lambda kv: (getattr(kv[1].element, "doc_id", ""), getattr(kv[1].element, "page_no", 0),
                                                       getattr(kv[1].element, "idx", 0)))
    for eid, ev in ranked:
        quotes = [q for q in (ev.quotes or []) if q and q.strip()]
        section = getattr(ev.element, "section", "") or ""
        cursor=0
        for sid, sentence in spans[eid].items():
            raw=getattr(ev.element,'text','');offset=raw.find(sentence,cursor)
            if offset<0:continue
            cursor=offset+len(sentence)
            if quotes and not any(sentence.strip() in q or q.strip() in sentence for q in quotes):
                continue  # only sentences the verifier kept as support
            parent=getattr(ev.element,'parent_element_id',None) or getattr(ev.element,'element_id','')
            scope=(getattr(ev.element,'doc_id',''),section,parent)
            key = (*scope,getattr(ev.element,'char_start',0)+offset)
            if key in seen or not is_fact(sentence):
                continue
            seen.add(key)
            tagged = sorted((r for r in getattr(ev, "requirement_ids", []) or [] if r in order), key=order.get)
            topic = tagged[0] if tagged else None
            if topic is None:
                hits = [t for t in topics if words(t["text"]) & words(sentence + " " + section)]
                topic = hits[0]["id"] if hits else None
            # Restored verbatim, a sentence that leans on the previous one ("It took ...") keeps that sentence.
            ids = list(spans[eid])
            if getattr(ev.element, "kind", "text") == "table":
                context = [ids[0]] if sid != ids[0] else []  # a table row is restored with its caption and header
            else:
                context = [ids[ids.index(sid)-1]] if LEANS.match(sentence.lstrip()) and ids.index(sid) > 0 else []
            facts.append({"id": f"F{len(facts)+1}", "evidence_id": eid, "span_id": sid, "context_span_ids": context,
                          "text": display_source(sentence), "topic": topic or (ev.aspect_ids[0] if ev.aspect_ids else ""),
                          "doc_id": getattr(ev.element, "doc_id", ""), "page": getattr(ev.element, "page_no", None),
                          "section": section,"scope":scope,"char_start":getattr(ev.element,'char_start',0)+offset,
                          "context_chars":sum(len(spans[eid][c]) for c in context)})
    return facts
